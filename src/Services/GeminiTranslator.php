use VigStudio\VigAutoTranslations\Contracts\Translator;

/**
 * Use Google Gemini API for translation
 *
 * https://ai.google.dev/docs
 */
class GeminiTranslator implements Translator
{
    public function translate(string $source, string $target, string $value): ?string
    {
        $apiKey = setting('vig_translate_gemini_key', config('plugins.vig-auto-translations.general.gemini_key'));
        $model = setting('vig_translate_gemini_model', config('plugins.vig-auto-translations.general.gemini_model', 'gemini-pro'));

        if (empty($apiKey)) {
            return $value;
        }

        // Map language codes to language names
        $languageNames = $this->getLanguageNames();
        $sourceLanguage = $languageNames[$source] ?? $source;
        $targetLanguage = $languageNames[$target] ?? $target;

        $prompt = sprintf(
            'Translate from %s to %s. Only return the translated text, nothing else.%s%s: %s',
            $sourceLanguage,
            $targetLanguage,
            PHP_EOL,
            $targetLanguage,
            $value
        );

        $response = Http::withoutVerifying()
            ->asJson()
            ->post("https://generativelanguage.googleapis.com/v1beta/models/{$model}:generateContent?key={$apiKey}", [
                'contents' => [
                    [
                        'parts' => [
                            ['text' => $prompt],
                        ],
                    ],
                ],
                'generationConfig' => [
                    'temperature' => 0.3,
                    'maxOutputTokens' => 1000,
                ],
            ]);

        if ($response->failed()) {
            return $value;
        }

        $translated = $response->json('candidates.0.content.parts.0.text');

        return Str::squish($translated ?: $value);
    }

